/* ── GF(2^8) multiply for the linear layer ────────────────────────────────── */

static uint8_t gf_mul8(uint8_t a, uint8_t b)
{
    uint8_t r = 0;
    for (int i = 0; i < 8; i++)
    {
        if (b & 1U)
        {
            r ^= a;
        }
        uint8_t hi = (uint8_t)(a & 0x80U);
        a <<= 1;
        if (hi)
        {
            a ^= 0xC3U;    /* polynomial x^8 + x^7 + x^6 + x + 1 */
        }
        b >>= 1;
    }
    return r;
}

