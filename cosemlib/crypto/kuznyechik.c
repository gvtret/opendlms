/* ── Linear transformation L: shift + LFSR feedback ──────────────────────── */

static void kuznyechik_L(uint8_t state[16])
{
    for (int j = 0; j < 16; j++)
    {
        /* Shift left one byte (big-endian) and insert feedback at right */
        uint8_t x = state[15];
        for (int i = 15; i > 0; i--)
        {
            state[i] = state[i - 1];
        }
        state[0] = x;

        /* LFSR feedback: XOR each byte with l_vec[i] */
        for (int i = 0; i < 16; i++)
        {
            state[i] ^= l_vec[i];
        }
    }
}

/* ── Key schedule (fuzzing function) ─────────────────────────────────────── */

static void kuznyechik_fuzz(uint8_t key[32], const uint8_t rc[16])
{
    /* X with round constant */
    for (int i = 0; i < 16; i++)
    {
        key[i] ^= rc[i];
    }

    /* Apply S */
    for (int i = 0; i < 16; i++)
    {
        key[i] = sbox[key[i]];
    }

    /* Apply L */
    kuznyechik_L(key);

    /* XOR with second half of key */
    for (int i = 0; i < 16; i++)
    {
        key[16 + i] ^= key[i];
    }
}

/* ── Public API ───────────────────────────────────────────────────────────── */

void kuznyechik_init(kuznyechik_context *ctx)
{
    memset(ctx, 0, sizeof(*ctx));
}

void kuznyechik_free(kuznyechik_context *ctx)
{
    memset(ctx, 0, sizeof(*ctx));
}

int kuznyechik_setkey_enc(kuznyechik_context *ctx, const uint8_t key[32])
{
    /* Copy key into working buffer */
    uint8_t k[32];
    memcpy(k, key, 32);

    /* Store first two round keys */
    memcpy(ctx->rk, k, 16);
    memcpy(ctx->rk + 16, k + 16, 16);

    /* Generate remaining round keys via iterative fuzzing */
    for (int i = 0; i < 8; i++)
    {
        kuznyechik_fuzz(k, iter_c[i * 4]);
        memcpy(ctx->rk + 32 + (i * 4) * 16, k, 16);
        memcpy(ctx->rk + 32 + (i * 4 + 1) * 16, k + 16, 16);

        kuznyechik_fuzz(k, iter_c[i * 4 + 1]);
        memcpy(ctx->rk + 32 + (i * 4 + 2) * 16, k, 16);
        memcpy(ctx->rk + 32 + (i * 4 + 3) * 16, k + 16, 16);
    }

    return 0;
}

void kuznyechik_crypt_ecb(const kuznyechik_context *ctx,
                           const uint8_t input[16],
                           uint8_t output[16])
{
    uint8_t state[16];
    memcpy(state, input, 16);

    /* 9 rounds of X → S → L */
    for (int i = 0; i < 9; i++)
    {
        /* X: XOR state with round key */
        for (int j = 0; j < 16; j++)
        {
            state[j] ^= ctx->rk[(i + 1) * 16 + j];
        }

        /* S: apply substitution */
        for (int j = 0; j < 16; j++)
        {
            state[j] = sbox[state[j]];
        }

        /* L: linear transformation */
        kuznyechik_L(state);
    }

    /* Final round: X only */
    for (int j = 0; j < 16; j++)
    {
        state[j] ^= ctx->rk[0 + j];
    }

    memcpy(output, state, 16);
}
