static void kuznyechik_inv_substitution(uint8_t b[16])
{
    for (int i = 0; i < 16; i++)
        b[i] = inv_sbox[b[i]];
}

/* L vector from RFC 7801 §4.2 (l_0..l_15) */
static const uint8_t l_vec[16] = {
    0x94,0x20,0x85,0x10,0xC2,0xC0,0x01,0xFB,
    0x01,0xC0,0xC2,0x10,0x85,0x20,0x94,0x01
};

/* L = R^16, where R shifts right by one byte and applies l.
 * l(a_15,...,a_0) = Σ l_i ⊗ a_i in GF(2^8) */
static void kuznyechik_L(uint8_t b[16])
{
    for (int j = 0; j < 16; j++)
    {
        uint8_t v = 0;
        for (int i = 0; i < 16; i++)
            v ^= gf_mul_c3(b[i], l_vec[i]);
        memmove(b + 1, b, 15);
        b[0] = v;
    }
}

/* GF(2^8) multiplicative inverse under 0xC3 */
static uint8_t gf_inv_c3(uint8_t a)
{
    if (a == 0) return 0;
    for (int i = 1; i < 256; i++)
        if (gf_mul_c3(a, (uint8_t)i) == 1)
            return (uint8_t)i;
    return 0;
}

static const uint8_t l15_inv = 0x01; /* gf_inv_c3(l_vec[15]) = gf_inv_c3(0x01) = 0x01 */

/* Inverse L = (R^{-1})^16. R^{-1} shifts left and computes the lost byte. */
static void kuznyechik_inv_linear(uint8_t b[16])
{
    for (int j = 0; j < 16; j++)
    {
        uint8_t v = b[0];
        for (int i = 0; i < 15; i++)
            v ^= gf_mul_c3(b[i + 1], l_vec[i]);
        v = gf_mul_c3(v, l15_inv);
        memmove(b, b + 1, 15);
        b[15] = v;
    }
}

/* Round constants C_i = L(Vec_128(i)), i=1..32 */
static void compute_c(uint8_t c[16], uint32_t i)
{
    memset(c, 0, 16);
    /* Big-endian encoding of 128-bit integer i */
    c[15] = (uint8_t)i;
    c[14] = (uint8_t)(i >> 8);
    c[13] = (uint8_t)(i >> 16);
    c[12] = (uint8_t)(i >> 24);
    kuznyechik_L(c);
}

/* F-function: F[k](a_1, a_0) = (LSX[k](a_1) XOR a_0, a_1)
 * Input:  k[0..15] = a_1, k[16..31] = a_0
 * Output: k[0..15] = LSX(C)(a_1) XOR a_0, k[16..31] = a_1 */
static void kuznyechik_f(uint8_t k[32], const uint8_t c[16])
{
    uint8_t saved_a1[16];
    memcpy(saved_a1, k, 16);       /* save a_1 */
    /* LSX[C](a_1) = L(S(a_1 XOR C)) */
    for (int i = 0; i < 16; i++)
        k[i] ^= c[i];
    for (int i = 0; i < 16; i++)
        k[i] = sbox[k[i]];
    kuznyechik_L(k);
    /* XOR with a_0 */
    for (int i = 0; i < 16; i++)
        k[i] ^= k[16 + i];
    /* new_a_0 = old_a_1 */
    memcpy(k + 16, saved_a1, 16);
}

void kuznyechik_init(kuznyechik_context *ctx)
{
    memset(ctx, 0, sizeof(*ctx));
}

void kuznyechik_free(kuznyechik_context *ctx)
{
    memset(ctx, 0, sizeof(*ctx));
}

int kuznyechik_setkey_enc(kuznyechik_context *ctx, const uint8_t key[32])
{
    uint8_t ab[32]; /* a_1=a[0..15], a_0=a[16..31] */
    memcpy(ab, key, 16);       /* a_1 = K_1 */
    memcpy(ab + 16, key + 16, 16); /* a_0 = K_2 */

    memcpy(ctx->rk, ab, 16);       /* K_1 */
    memcpy(ctx->rk + 16, ab + 16, 16); /* K_2 */

    /* RFC 7801 §4.4: 4 groups of 8 F-function calls */
    for (int i = 0; i < 4; i++)
    {
        for (int j = 0; j < 8; j++)
        {
            uint8_t c[16];
            compute_c(c, 8 * i + j + 1);
            kuznyechik_f(ab, c);
        }
        memcpy(ctx->rk + (2 * i + 2) * 16, ab, 16);
        memcpy(ctx->rk + (2 * i + 3) * 16, ab + 16, 16);
    }
    return 0;
}

void kuznyechik_crypt_ecb(const kuznyechik_context *ctx,
                           const uint8_t input[16],
                           uint8_t output[16])
{
    uint8_t b[16];
    memcpy(b, input, 16);
    /* 9 rounds of X → S → L */
    for (int r = 0; r < 9; r++)
    {
        for (int i = 0; i < 16; i++)
            b[i] ^= ctx->rk[r * 16 + i];
        for (int i = 0; i < 16; i++)
            b[i] = sbox[b[i]];
        kuznyechik_L(b);
    }
    /* Final round key addition */
    for (int i = 0; i < 16; i++)
        b[i] ^= ctx->rk[144 + i];
    memcpy(output, b, 16);
}

void kuznyechik_decrypt_ecb(const kuznyechik_context *ctx,
                            const uint8_t input[16],
                            uint8_t output[16])
{
    uint8_t b[16];
    memcpy(b, input, 16);
    /* RFC 7801 §4.5.2: D = X_K1 · L⁻¹S⁻¹X_K2 · ... · L⁻¹S⁻¹X_K10 */
    for (int i = 0; i < 16; i++)
        b[i] ^= ctx->rk[144 + i];  /* X_K10 */
    for (int r = 8; r >= 0; r--)    /* L⁻¹S⁻¹X_K9 .. L⁻¹S⁻¹X_K1 */
    {
        kuznyechik_inv_linear(b);
        kuznyechik_inv_substitution(b);
        for (int i = 0; i < 16; i++)
            b[i] ^= ctx->rk[r * 16 + i];
    }
    memcpy(output, b, 16);
}
