/* GF(2^8) with polynomial 0xC3 (x^8+x^7+x^6+x+1) for L transform */
static uint8_t gf_mul_c3(uint8_t a, uint8_t b)
{
    uint8_t r = 0;
    for (int i = 0; i < 8; i++)
    {
        if (b & 1) r ^= a;
        int hi = a & 0x80;
        a <<= 1;
        if (hi) a ^= 0xC3;
        b >>= 1;
    }
    return r;
}

